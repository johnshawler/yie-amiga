#!/usr/bin/env python3
"""Build-time conversion of the Yie Ar Kung-Fu graphics ROMs into the planar tables used by the Amiga renderer.
usage: mkgfx.py out_dir      -> out_dir/gfx.bin (tiles then sprites) and out_dir/palette.h
 tiles   : 512 x 8 rows x 4 plane bytes (plane 0..3 = pen bits 0..3, bit 7 = leftmost pixel)                 = 16384 bytes
 sprites : 512 x 16 rows x 4 plane words (big endian, bit 15 = leftmost pixel)                               = 65536 bytes
 palette : 32 x 0x00RRGGBB from the colour PROM (pinned-driver weights)"""
import sys, os, struct
sys.path.insert(0, os.path.dirname(__file__))
import gfxdec

def main():
    out = sys.argv[1]; os.makedirs(out, exist_ok=True)
    T = gfxdec.decode_tiles(); S = gfxdec.decode_sprites()
    b = bytearray()
    for ch in T:
        for y in range(8):
            for p in range(4):
                v = 0
                for x in range(8): v |= ((ch[y][x] >> p) & 1) << (7 - x)
                b.append(v)
    for ch in S:
        for y in range(16):
            for p in range(4):
                v = 0
                for x in range(16): v |= ((ch[y][x] >> p) & 1) << (15 - x)
                b += struct.pack('>H', v)
    open(os.path.join(out, 'gfx.bin'), 'wb').write(bytes(b))
    pal = gfxdec.palette('pinned')
    with open(os.path.join(out, 'palette.h'), 'w') as f:
        f.write('/* generated by tools/mkgfx.py from the colour PROM 407c10.1g */\nstatic const unsigned long yie_palette[32] = {\n')
        for i in range(0, 32, 4): f.write('    ' + ', '.join('0x%06X' % ((r << 16) | (g << 8) | bl) for r, g, bl in pal[i:i + 4]) + ',\n')
        f.write('};\n')
    print("gfx.bin", len(b), "bytes")
main()

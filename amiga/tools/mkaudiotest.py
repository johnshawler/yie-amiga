#!/usr/bin/env python3
"""Audio self-test script: a fixed sequence of SN76489A writes and speech phrases (no game).  Writes audiotest_script.h (for the AUDIOTEST build of the Amiga
   program) and audiotest.io (yref-style I/O log for sound/sndpc.c, which produces the expected stream).  usage: mkaudiotest.py outdir"""
import sys, os
out = sys.argv[1]
W = []        # (cycle, byte)
S = []        # (cycle, phrase)
def wr(frame, off, *bytes_):
    c = frame * 25344 + off
    for b in bytes_:
        W.append((c, b)); c += 100
def tone(ch, period): return [0x80 | (ch * 2) << 4 | (period & 15), (period >> 4) & 0x3F]
def vol(ch, att): return [0x80 | (ch * 2 + 1) << 4 | att]
for ch in range(4): wr(2, 500 + ch * 300, *vol(ch, 15))
# 1. a 750 Hz tone (period 64) on channel 0 at full volume for 1.5 s, then a 3 kHz tone at -10 dB
wr(30, 1000, *tone(0, 64), *vol(0, 0))
wr(120, 2000, *tone(0, 16), *vol(0, 5))
wr(180, 0, *vol(0, 15))
# 2. three channels with different periods and volumes
wr(200, 700, *tone(0, 100), *vol(0, 2), *tone(1, 150), *vol(1, 6), *tone(2, 211), *vol(2, 10))
wr(300, 0, *vol(0, 15), *vol(1, 15), *vol(2, 15))
# 3. noise: white noise, rate 0..2 and tone-2-controlled, with sweeps of volume
wr(320, 1234, 0xE4, *vol(3, 0))             # white noise, fastest
wr(380, 0, 0xE5)                            # medium
wr(440, 0, 0xE6, *vol(3, 6))                # slowest, -12 dB
wr(500, 0, 0xE7, *tone(2, 40), *vol(3, 3))  # noise clocked by tone 2
wr(560, 0, *vol(3, 15))
# 4. speech: phrases at various offsets inside the frame, one of them cut by the next
for k, (fr, off, ph) in enumerate([(600, 5000, 7), (780, 13000, 8), (1000, 21000, 1), (1100, 100, 6)]):
    S.append((fr * 25344 + off, ph))
wr(1300, 0, *tone(0, 80), *vol(0, 3))      # a tone under a speech phrase
S.append((1310 * 25344 + 9000, 3))
wr(1500, 0, *vol(0, 15))
NF = 1560
with open(os.path.join(out, 'audiotest.io'), 'w') as f:
    ev = sorted([(c, 'w', b) for c, b in W] + [(c, 's', p) for c, p in S])
    for c, k, v in ev:
        if k == 'w':
            f.write("W %d 4800 %02x\n" % (c, v)); f.write("W %d 4900 %02x\n" % (c + 5, v))
        else:
            f.write("W %d 4b00 %02x\n" % (c - 12, (v << 1) & 0xFF)); f.write("W %d 4a00 03\n" % c); f.write("W %d 4a00 00\n" % (c + 40))
with open(os.path.join(out, 'audiotest_script.h'), 'w') as f:
    f.write("/* generated by tools/mkaudiotest.py */\n#define AT_FRAMES %d\n" % NF)
    f.write("static const struct { uint32_t cycle; uint8_t kind, data; } at_script[] = {\n")
    for c, k, v in ev:
        f.write("    { %du, %d, %d },\n" % (c, 0 if k == 'w' else 1, v))
    f.write("    { 0xFFFFFFFFu, 0, 0 } };\n")
print("script: %d chip writes, %d speech starts, %d frames" % (len(W), len(S), NF))

#!/usr/bin/env python3
"""inputs.txt (yref -i format) -> soak_script.h for the SOAK build of the Amiga program, plus the reference CRCs of the RAM at the check frames.
   usage: mksoak.py inputs.txt yref_dump.bin outdir f1 f2"""
import sys, struct, zlib
inp, dump, out, f1, f2 = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]), int(sys.argv[5])
ev = [tuple(int(x, 16) if i else int(x) for i, x in enumerate(l.split()[:3])) for l in open(inp) if l.strip()]
with open(out + '/soak_script.h', 'w') as f:
    f.write("/* generated by tools/mksoak.py */\n#define SOAK_F1 %d\n#define SOAK_F2 %d\nstatic const struct { uint16_t frame; uint8_t sys, p1; } soak_script[] = {\n" % (f1, f2))
    for fr, sy, p1 in ev: f.write("    { %d, 0x%02X, 0x%02X },\n" % (fr, sy, p1))
    f.write("    { 65535, 0xFF, 0xFF } };\n")
d = open(dump, 'rb').read(); rec = 4 + 8 + 10 + 4 + 4096
for fr in (f1, f2):
    ram = d[fr * rec + 26: fr * rec + 26 + 4096]
    print("frame %d: RAM $5000-$5FFF CRC32 = %08X" % (fr, zlib.crc32(ram) & 0xFFFFFFFF))
